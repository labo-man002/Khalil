function recognizePattern(opening, before, after, { rumor, final }) {
  let revision;
  if (after.interpretation === 'missing') {
    revision = ['الراي ما مشاش مع الكشف', 'آخر راي قلتو هو اللي الفلوس خرجت. ورقة البنك تورّي العكس. اسأل روحك: الورقة هاذي تأكّد كلامي وإلّا تنقضو؟'];
  } else if (after.interpretation === 'unknown') {
    revision = ['خلّيت السؤال مفتوح', 'قلت اللي مازال الكشف موش واضح عندك. جرّب تقارن السطرين: نقص نفس المبلغ من القفف وزاد في التوصيل. شكون كتب الملاحظة وعلاش، هاذي حكاية أخرى ما يجاوبش عليها البنك.'];
  } else if (before.interpretation === 'moved') {
    revision = ['نفس الراي، بدليل جديد', 'بقيت على فكرة اللي المبلغ تبدّل في الجدول. قبل كانت تخميمة، وبعد كشف البنك ولّت مسنودة بدليل.'];
  } else {
    revision = ['الدليل بدّل وجهة نظرك', 'بدّلت التفسير بعد ما شفت كشف البنك. في الواقع، اسأل روحك شنوّة المعلومة اللي كان تظهر تنجّم تبدّل رايك.'];
  }

  let action;
  if (rumor === 'share' && after.interpretation === 'moved') {
    action = ['تثبّتّ من الفلوس، واستعجلت في الكلام', 'في الحساب، فرّقت بين رقم في الجدول وفلوس خرجت بالحقّ. مع أمينة وافقت توصل الجملة قبل ما تتثبّت شكون قالها. تنجّم تعطي لصحة الكلام على الناس نفس الوقت اللي عطيتو للأرقام.'];
  } else if (final === 'post') {
    action = ['اخترت تتحرّك بسرعة', 'بعثت الزوز نسخ للغروب باش توصل للناس بسرعة. تصويرة السطر دارت وحدها. قبل ما تبعث دليل، خمّم كان ينجم يتفهم من غير تفسيرك.'];
  } else if (rumor === 'share') {
    action = ['الكلام دار قبل التثبّت', 'وافقت أمينة توصل الجملة قبل ما تتثبّت شكون قالها. كان تدور الجملة وحدها، شكون ينجم يرجّعها لأصلها؟'];
  } else if (final === 'internal') {
    action = ['عطيت الأولويّة للورق وللجنة', 'مع أمينة خليت الكلام على يوسف يتسنّى، وفي الآخر خليت اللجنة تراجع الورق. هكّا خذيت وقت للتثبّت، أمّا اللوم اللي صار قدّام الناس مازال ما تصلّحش قدّامهم.'];
  } else {
    action = ['فرّقت بين التصحيح والكلام اللي يدور', 'مع أمينة خليت الكلام على يوسف يتسنّى. وبعد ما شفت الورق، طلبت من يوسف يصحّح اللي قالو قدّام نفس الناس. تنجّم تواجه غلطة ثابتة وتخلّي نيّة اللي عملها مفتوحة.'];
  }
  return [openingPatterns[opening.interpretation], revision, action];
}

